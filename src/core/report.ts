import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { Finding, Severity } from "./model.js";
import { homeDir } from "./snapshot.js";

// A QA sign-off record for a campaign or journey: what was checked, what was found, what couldn't be
// verified, and a place for a reviewer to approve. Written as Markdown so it pastes into a ticket,
// Slack, Confluence or Notion as-is.

export interface CampaignResult {
  kind: string;
  id: string;
  name: string;
  status: string;
  settings: Finding[];
  messages: { name: string; summary: Record<Severity, number>; findings: Finding[]; waived?: { finding: Finding; reason: string }[] }[];
  notVerified: string[];
  summary: Record<Severity, number>;
  snapshotTakenAt: string;
}

const ICON: Record<Severity, string> = { fail: "🔴", warn: "🟡", info: "ℹ️" };
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function verdict(summary: Record<Severity, number>): string {
  if (summary.fail) return `🔴 Don't launch: ${summary.fail} blocking problem${summary.fail > 1 ? "s" : ""}`;
  if (summary.warn) return `🟡 Fix first: ${summary.warn} warning${summary.warn > 1 ? "s" : ""}`;
  return "🟢 Ready";
}

export function signOffMarkdown(r: CampaignResult, ctx: { platform: string; operator: string; checkedAt: Date; version: string }): string {
  const rows = (findings: Finding[]) =>
    findings.map((f) => `| ${ICON[f.severity]} ${f.severity} | \`${f.checkId}\` | ${cell(f.message)} | ${cell(f.fix ?? "")} |`).join("\n");
  const table = (findings: Finding[]) =>
    findings.length ? `| Severity | Check | What we found | Fix |\n|---|---|---|---|\n${rows(findings)}` : "No problems found.";

  const out: string[] = [
    `# QA sign-off: ${r.name}`,
    "",
    `**${verdict(r.summary)}**`,
    "",
    `| | |`,
    `|---|---|`,
    `| ${r.kind === "journey" ? "Journey" : "Campaign"} | ${cell(r.name)} (\`${r.id}\`, ${r.status}) |`,
    `| Platform | ${ctx.platform} |`,
    `| Checked by | ${cell(ctx.operator)}, ${ctx.checkedAt.toISOString().slice(0, 16).replace("T", " ")} UTC |`,
    `| Account snapshot | ${r.snapshotTakenAt.slice(0, 16).replace("T", " ")} UTC |`,
    `| Totals | ${r.summary.fail} blocking · ${r.summary.warn} warnings · ${r.summary.info} notes, across ${r.messages.length} message${r.messages.length === 1 ? "" : "s"} |`,
    "",
    "## Settings and structure",
    "",
    table(r.settings),
  ];
  for (const m of r.messages) {
    out.push("", `## ${m.name}  ${verdict(m.summary)}`, "", table(m.findings));
    if (m.waived?.length) out.push("", "Waived by house rules:", ...m.waived.map((w) => `- \`${w.finding.checkId}\`: ${w.reason}`));
  }
  if (r.notVerified.length) out.push("", "## Not verified (check these by hand)", "", ...r.notVerified.map((n) => `- [ ] ${n}`));
  out.push(
    "",
    "## Sign-off",
    "",
    "- [ ] Blocking problems fixed, or launch deferred",
    "- [ ] Warnings fixed or accepted with a reason",
    "- [ ] Test send reviewed on desktop and mobile",
    "",
    "Reviewer: ______________________  Date: __________  Approved to launch: ☐ Yes ☐ No",
    "",
    `<sub>Generated by crm-lifecycle-ops ${ctx.version}. Pass/fail calls are made by rule-based checks, not AI.</sub>`,
    "",
  );
  return out.join("\n");
}

/** Saves the report under ~/.crm-lifecycle-ops/reports/ and returns the path. */
export async function saveSignOff(r: CampaignResult, markdown: string, at: Date): Promise<string> {
  const dir = join(homeDir(), "reports");
  await mkdir(dir, { recursive: true });
  const slug =
    r.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 60) || r.id;
  const path = join(dir, `${slug}-${at.toISOString().slice(0, 16).replace(/[:T]/g, "-")}.md`);
  await writeFile(path, markdown, "utf8");
  return path;
}
